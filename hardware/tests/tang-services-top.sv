// Test-only muxes expose independent UART, packet, loader and memory boundaries.
// No behavioral RAM replacement or shadow implementation of the DUT is here.
module tang_services_top (
    input wire clk, reset, rx,
    output wire tx,
    input wire tx_test, tx_test_valid,
    input wire [7:0] tx_test_data,
    output wire tx_test_ready,
    output wire [7:0] uart_received,
    output wire uart_received_valid, uart_error,
    input wire direct_command, direct_valid,
    input wire [7:0] direct_opcode,
    input wire [23:0] direct_address,
    input wire [15:0] direct_data,
    output wire command_done, command_error,
    output wire packet_command, protocol_error,
    output wire [31:0] status,
    output wire running, loading, bios_valid, image_valid,
    output wire [8:0] buttons,
    output wire [19:0] romsize,
    output wire [20:0] image_bytes,
    output wire [8:0] bios_address,
    output wire [7:0] bios_data,
    output wire bios_write,
    output wire [19:0] rom_address,
    output wire [15:0] rom_data,
    output wire rom_write,
    input wire memory_test, memory_grant, test_request, test_write,
    input wire [22:0] test_address,
    input wire [31:0] test_data,
    input wire [3:0] test_mask,
    output wire request_ready, response, initialized,
    output wire [31:0] read_data,
    output wire loader_request, loader_ready,
    output wire [22:0] loader_address,
    output wire [31:0] loader_data,
    output wire [3:0] loader_mask,
    input wire cart_test_request,
    input wire [19:0] cart_test_address,
    output wire cart_test_ack,
    output wire [7:0] cart_test_byte,
    output wire bridge_fault,
    output wire bus_request, bus_write,
    output wire [22:0] bus_address,
    output wire [31:0] bus_data,
    output wire [3:0] bus_mask,
    output wire [10:0] sdram_a,
    output wire [1:0] sdram_ba,
    output wire [3:0] sdram_dqm,
    output wire sdram_cke, sdram_cs_n, sdram_ras_n, sdram_cas_n, sdram_we_n,
    input wire [31:0] dq_in,
    output wire [31:0] dq_out,
    output wire dq_oe
);
    wire [7:0] packet_tx, opcode;
    wire [23:0] packet_address;
    wire [15:0] packet_data;
    wire packet_tx_valid;
    wire bridge_response;
    lynx_uart uart (.clk(clk),.reset(reset),.rx(rx),.tx(tx),
        .rx_data(uart_received),.rx_valid(uart_received_valid),.framing_error(uart_error),
        .tx_data(tx_test ? tx_test_data:packet_tx),
        .tx_valid(tx_test ? tx_test_valid:packet_tx_valid),.tx_ready(tx_test_ready));
    lynx_packet packet (.clk(clk),.reset(reset),.rx_data(uart_received),
        .rx_valid(uart_received_valid),.rx_error(uart_error),
        .command_valid(packet_command),.command(opcode),.address(packet_address),.data(packet_data),
        .command_done(command_done && !direct_command),.command_error(command_error),.status(status),
        .tx_data(packet_tx),.tx_valid(packet_tx_valid),.tx_ready(tx_test_ready && !tx_test),
        .protocol_error(protocol_error));
    lynx_loader loader (.clk(clk),.reset(reset),
        .command_valid(direct_command ? direct_valid:packet_command),
        .command(direct_command ? direct_opcode:opcode),
        .address(direct_command ? direct_address:packet_address),
        .data(direct_command ? direct_data:packet_data),
        .command_done(command_done),.command_error(command_error),
        .memory_initialized(initialized),.protocol_error(protocol_error),.presentation_status({2'b0,bridge_fault,4'b0}),
        .status(status),.running(running),.loading(loading),.bios_valid(bios_valid),
        .image_valid(image_valid),.buttons(buttons),.romsize(romsize),.image_bytes(image_bytes),
        .memory_request(loader_request),.memory_ready(loader_ready),
        .memory_response(bridge_response),.memory_address(loader_address),
        .memory_data(loader_data),.memory_mask(loader_mask),
        .bios_address(bios_address),.bios_data(bios_data),.bios_write(bios_write),
        .rom_address(rom_address),.rom_data(rom_data),.rom_write(rom_write));
    lynx_cart_bridge bridge (.clk(clk),.reset(reset),.running(running),
        .load_request(loader_request),.load_address(loader_address),.load_data(loader_data),.load_mask(loader_mask),
        .load_ready(loader_ready),.load_response(bridge_response),
        .cart_request(cart_test_request),.cart_address(cart_test_address),
        .cart_ack(cart_test_ack),.cart_byte(cart_test_byte),.protocol_fault(bridge_fault),
        .memory_request(bus_request),.memory_ready(request_ready && memory_grant && !memory_test),
        .memory_response(response && !memory_test),.memory_read_data(read_data),
        .memory_write(bus_write),.memory_address(bus_address),.memory_data(bus_data),.memory_mask(bus_mask));
    lynx_sdram memory (.clk(clk),.reset(reset),
        .request(memory_test ? test_request:(bus_request && memory_grant)),
        .request_ready(request_ready),.write(memory_test ? test_write:bus_write),
        .address(memory_test ? test_address:bus_address),
        .write_data(memory_test ? test_data:bus_data),
        .write_mask(memory_test ? test_mask:bus_mask),
        .response(response),.read_data(read_data),.initialized(initialized),
        .sdram_a(sdram_a),.sdram_ba(sdram_ba),.sdram_dqm(sdram_dqm),
        .sdram_cke(sdram_cke),.sdram_cs_n(sdram_cs_n),
        .sdram_ras_n(sdram_ras_n),.sdram_cas_n(sdram_cas_n),.sdram_we_n(sdram_we_n),
        .dq_in(dq_in),.dq_out(dq_out),.dq_oe(dq_oe));
endmodule
