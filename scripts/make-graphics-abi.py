"""Generate the enhanced graphics MMIO constants for ca65 firmware and RTL.

Usage: make-graphics-abi.py graphics-abi.json OUTPUT_DIRECTORY
The checked-in copies are compared with this output by the graphics-abi check.
"""
from pathlib import Path
import json
import sys

source, destination = Path(sys.argv[1]), Path(sys.argv[2])
abi = json.loads(source.read_text())
destination.mkdir(parents=True, exist_ok=True)


def number(value):
    return int(value, 0) if isinstance(value, str) else int(value)


base = number(abi["base"])
size = number(abi["descriptor_bytes"])
notice = "Generated by scripts/make-graphics-abi.py from hardware/enhanced/graphics-abi.json. Do not edit."

asm = [f"; {notice}", f"GFX_BASE = ${base:04x}"]
asm += [f"GFX_{name} = ${base + number(offset):04x}" for name, offset in abi["registers"].items()]
asm += [f"GFX_DEVICE_ID = ${number(abi['device_id']):02x}", f"GFX_REVISION_VALUE = {number(abi['revision'])}",
        f"GFX_DESCRIPTOR_BYTES = {size}"]
asm += [f"GFX_STATUS_{name} = ${1 << number(bit):02x}" for name, bit in abi["status_bits"].items()]
asm += [f"GFX_CONTROL_{name} = ${1 << number(bit):02x}" for name, bit in abi["control_bits"].items()]
asm += [f"GFX_OP_{name} = {number(value)}" for name, value in abi["operations"].items()]
asm += [f"GFX_ERROR_{name} = {number(value)}" for name, value in abi["errors"].items()]
asm += [f"GFX_FIELD_{name} = {number(value)}" for name, value in abi["descriptor_fields"].items()]
(destination / "graphics-abi.inc").write_text("\n".join(asm) + "\n")

sv = [f"// {notice}",
      "// The package describes the whole ABI; a given design uses part of it.",
      "/* verilator lint_off UNUSEDPARAM */", "package cb_abi_pkg;",
      f"    localparam logic [7:0] BASE_PAGE = 8'h{base >> 8:02x};"]
sv += [f"    localparam logic [7:0] REG_{name} = 8'h{number(offset):02x};" for name, offset in abi["registers"].items()]
sv += [f"    localparam logic [7:0] DEVICE_ID = 8'h{number(abi['device_id']):02x};",
       f"    localparam logic [7:0] REVISION = 8'd{number(abi['revision'])};",
       f"    localparam integer DESCRIPTOR_BYTES = {size};"]
sv += [f"    localparam integer CONTROL_{name} = {number(bit)};" for name, bit in abi["control_bits"].items()]
sv += [f"    localparam logic [1:0] OP_{name} = 2'd{number(value)};" for name, value in abi["operations"].items()]
sv += [f"    localparam logic [2:0] ERROR_{name} = 3'd{number(value)};" for name, value in abi["errors"].items()]
sv += [f"    localparam integer FIELD_{name} = {number(value)};" for name, value in abi["descriptor_fields"].items()]
sv.append("endpackage")
sv.append("/* verilator lint_on UNUSEDPARAM */")
(destination / "cb_abi_pkg.sv").write_text("\n".join(sv) + "\n")

descriptor = number(abi["registers"]["DESCRIPTOR"])
if base & 0xff or descriptor % 64 or size > 64 or descriptor + size > 256:
    raise SystemExit("MMIO window must be one page; the descriptor must start on a 64-byte boundary inside it")
