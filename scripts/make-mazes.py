"""Author reproducible circuit mazes and shortest-path tables for the 65C02 ROM.

This is a build-time asset tool. Runtime movement and AI execute on the CPU.
"""
from collections import deque
from pathlib import Path
import random
import sys

DIRECTIONS = ((1, 1, 2), (-1, 2, 1), (8, 4, 8), (-8, 8, 4))


def neighbors(node):
    for delta, bit, opposite in DIRECTIONS:
        other = node + delta
        if 0 <= other < 32 and (abs(delta) == 8 or node // 8 == other // 8):
            yield other, bit, opposite


def maze(stage):
    rng = random.Random(0xC1AC017 + stage)
    edges = [0] * 32
    seen = {0}
    stack = [0]
    while stack:
        node = stack[-1]
        choices = [v for v in neighbors(node) if v[0] not in seen]
        if not choices:
            stack.pop()
            continue
        other, bit, opposite = rng.choice(choices)
        edges[node] |= bit
        edges[other] |= opposite
        seen.add(other)
        stack.append(other)
    extra = [(n, v, bit, opposite) for n in range(32)
             for v, bit, opposite in neighbors(n) if v > n and not edges[n] & bit]
    rng.shuffle(extra)
    for node, other, bit, opposite in extra[:(15, 12, 9, 7)[stage]]:
        edges[node] |= bit
        edges[other] |= opposite
    distances = []
    for start in range(32):
        row = [255] * 32
        row[start] = 0
        queue = deque([start])
        while queue:
            node = queue.popleft()
            for other, bit, opposite in neighbors(node):
                assert bool(edges[node] & bit) == bool(edges[other] & opposite)
                if edges[node] & bit and row[other] == 255:
                    row[other] = row[node] + 1
                    queue.append(other)
        assert max(row) < 32, "Every junction must be reachable"
        distances.extend(row)
    tiles = []
    assert max(distances) * 128 * 18 + 2000 < 65536, "Qualifying budget must fit 16 bits"
    for y in range(16):
        for x in range(32):
            cx, cy = x // 2, y // 2
            node = (cy // 2) * 8 + cx // 2
            walk = cx < 15 and cy < 7 and (
                (cx % 2 == 0 and cy % 2 == 0) or
                (cx % 2 == 1 and cy % 2 == 0 and edges[node] & 1) or
                (cx % 2 == 0 and cy % 2 == 1 and edges[node] & 4))
            tiles.append(1 if walk else 9)
    return edges, distances, tiles


def write(path):
    output = ["; Generated by scripts/make-mazes.py. SPDX-License-Identifier: GPL-2.0-or-later"]
    for name in ("masks", "distances", "tiles"):
        for stage in range(4):
            values = maze(stage)[("masks", "distances", "tiles").index(name)]
            output.append(f"maze_{name}_{stage}:")
            for offset in range(0, len(values), 16):
                output.append("    .byte " + ",".join(str(v) for v in values[offset:offset+16]))
    for name in ("masks", "distances", "tiles"):
        for part, operator in (("lo", "<"), ("hi", ">")):
            output.append(f"maze_{name}_{part}: .byte " + ",".join(
                f"{operator}maze_{name}_{stage}" for stage in range(4)))
    path.write_text("\n".join(output) + "\n")


if __name__ == "__main__":
    write(Path(sys.argv[1]))
